"""
One-shot recompute of every run's stored stats from its CSV, under the
current analysis definitions.

Re-run whenever a stats definition changes: because the stored numbers cannot
be recovered with pure SQL, every run's CSV is reloaded and re-summarized with
analysis.calculate_run_stats, the same function the live pipeline uses.

Four definitions have moved so far, and one column was added:

  * schema v3 changed what "present imagery" means — a pano the provider
    returned but whose capture date we couldn't read (status NO_DATE) now
    counts toward both coverage and pano totals instead of sitting in the
    status_other error bucket (see analysis.PRESENT_STATUSES).
  * issue #213 narrowed the capture-date columns to dates that can actually be
    true, and for gsv to official '© Google' imagery. This one must be applied
    to the WHOLE series in one pass: a half-recomputed city would show a run
    history mixing two definitions of "median age", which reads as a trend that
    never happened.
  * issue #226 widened what the LOADER can read. fileutils.load_city_csv_file
    parsed capture_date with a strict '%Y-%m-%d', so the legacy pre-2026 runs
    that carry MONTH precision (and are never rewritten) had every date coerced
    to NaT while their pano counts stayed perfect — catalog rows that looked
    fully populated with NULL oldest/newest/median. Note what that means for
    this script: it reads through the same loader, so the 2026-08-18 full-series
    #213 pass processed every affected run and left them NULL. A repair handle
    is only as permissive as its reader.
  * issue #367 narrowed what "covered" means for gsv: a pano beyond
    analysis.GSV_QUERY_RADIUS_M (50 m) of its query point is read as status
    OUT_OF_RADIUS, i.e. no pano for that point. The rule is applied by the same
    loader this script reads through, so the pass inherits it with no copy of
    its own; each report line names how many rows it reclassified. Measured on
    a 60-city archived sample, that is 10.4% of covered points -- a large move
    for a published coverage number, so this one too belongs to the WHOLE gsv
    series in one pass.
  * issue #289 (schema v20) ADDED runs.total_grid_points, the distinct
    (query_lat, query_lon) count, because total_points and the status_*
    buckets are ROW counts and a census run (mapillary, kartaview, panoramax)
    writes one row per image. No existing value moves; the column arrives NULL
    ("not measured") on every pre-v20 row, and this script is its backfill.
    It is a property of the CSV, so it is filled for every provider.
    Backfill it with `--only total_grid_points`, NOT a plain `--execute`:

      - The plain pass loads every CSV through the full loader. A census run is
        millions of rows (the PR #422 review put a 16.5M-row Mapillary run at
        ~15 GiB resident), on the host that runs the 02:00 batch. `--only`
        reads just the two coordinate columns (pandas `usecols`), which is the
        whole input the count needs.
      - The plain pass also applies every OTHER definition change the catalog
        has not yet taken. If that moves a capture-date column and
        --regenerate-json was not given, the catalog is repaired but the
        published per-run JSON is not -- and a later --regenerate-json pass can
        no longer find that run, because its date columns no longer move. That
        rebuild is lost for good. `--only` writes one column and nothing else,
        so no other repair is consumed by the backfill.

    Run it in the daytime, one --provider at a time, never overlapping the
    02:00 run-due (see docs/operations.md).

Columns refreshed per run: total_points, total_grid_points, status_ok, status_no_date,
status_zero_results, status_flat_only, status_out_of_radius, status_other,
unique_panos, unique_google_panos, coverage_rate_pct,
any_imagery_coverage_rate_pct, oldest/newest_capture_date,
median_pano_age_years, query_radius_m.

Per-run JSON summaries are not regenerated by default (they refresh on each
city's next run), but --regenerate-json rebuilds them for runs whose CSV holds
an implausible capture date, whose capture-date columns this pass moves, or
whose CSV holds a gsv pano beyond the query radius (issue #367).
Both are published files whose all_panos block and capture-year histogram hold
numbers we now know are wrong, and the city page reads them for the current AND
older snapshots. The second reason is not redundant with the first — see the
comment at the trigger itself: measured on issue #226's affected runs, 3 of 8
carried no impossible date at all, and rebuilding only on reason one would have
left them publishing NULL ages.

That second trigger has a size, and it is not small. It fires on ANY moved
capture-date column, so the first pass that also applies a date-definition
change rebuilds a large fraction of the series rather than the handful of runs
the definition was written for. Measured over every gsv run in a 1,157-run
catalog that had not yet taken issue #213's backfill: 405 runs, 35.0%, move a
date column — and only 8 of those are #226's. Each is a second full read of its
CSV on top of this loop's own, over a ~15 GB corpus. That is the cost of the
repair rather than a defect (those published files hold pre-#213 numbers), but
budget hours rather than minutes, and pass --provider gsv: without it the
trigger also reaches the Mapillary census runs, whose CSVs are millions of rows
apiece. Measurement and method: docs/experiments/capture-date-precision.md.

Two published artifacts are rebuilt either way, and they are not
interchangeable: cities.json.gz, which the overview site reads coverage from,
and driving_plan.json.gz, which is the ONLY published artifact that reads the
catalog columns this script repairs (json_summarizer._observation_block takes
newest_capture_date and median_pano_age_years straight from `runs`, while the
aggregate's age stats come from the per-run JSONs). Skipping it would leave
driving.html showing the pre-repair dates — and the driven_unplanned verdicts
derived from them — until some later unrelated `scheduler run-due`.

Idempotent: a run whose stored stats already match is left untouched. Runs
whose CSV is missing (skipped, reported) keep their existing values.

Usage:
    python scripts/recompute_run_stats.py                        # dry run
    python scripts/recompute_run_stats.py --execute              # apply
    python scripts/recompute_run_stats.py --provider gsv \\
        --regenerate-json --execute        # issue #213's and #226's repair on prod
    python scripts/recompute_run_stats.py --only total_grid_points   # #289 preview
    python scripts/recompute_run_stats.py --only total_grid_points \\
        --provider mapillary --execute     # issue #289's backfill, one provider at a time

--provider gsv is not just a filter there: --regenerate-json re-reads every
rebuilt run's CSV, and a Mapillary census run is millions of rows.
"""

